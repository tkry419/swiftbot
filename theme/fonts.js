// MAIN FONT FUNCTION
export function fancyText(text, style = 'bold') {
  if (!text) return ''

  const font = FONT_STYLES[style]
  if (!font) return text

  // Special case: strikethrough
  if (style === 'strike') {
    return text.split('').map(c => c + '\u0336').join('')
  }

  return text.split('').map(char => font.map[char] || char).join('')
}

