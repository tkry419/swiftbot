export function getAllFonts() {
  return Object.entries(FONT_STYLES).map(([key, font]) => ({
    id: key,
    name: font.name,
    example: fancyText('SwiftBot', key)
  }))
}

// QUOTE BLOCK - MONOSPACE STYLE
export function quoteBlock(text) {
  const lines = text.split('\n')
  return lines.map(line => `┃ ${line}`).join('\n')
}

// CODE BLOCK - MONOSPACE
export function codeBlock(text, lang = '') {
  return `\`\`\`${lang}\n${text}\n\`\`\``
}